def savefig(fig, name):
    """Save figure as both PNG and PDF."""
    for ext in ("png", "pdf"):
        path = os.path.join(OUT_DIR, name + "." + ext)
        fig.savefig(path, dpi=300, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print("  Saved: " + name + ".png / .pdf")



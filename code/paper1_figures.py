# FIGURE 6 (manuscript): Component Ratios by Region - Heatmap (2021)
# ======================================================================
def figure6():
    print("\nFigure 6: Component Ratios by Region Heatmap...")
    regions = [
        "Europe & Central Asia - WB",
        "North America",
        "East Asia & Pacific - WB",
        "Latin America & Caribbean - WB",
        "Middle East & North Africa - WB",
        "South Asia - WB",
        "Sub-Saharan Africa - WB",
    ]
    mask = (
        (qci_full["location_name"].isin(regions))
        & (qci_full["year"] == 2021)
        & (qci_full["age_name"] == "Age-standardized")
        & (qci_full["sex_name"] == "Both")
    )
    df = qci_full.loc[mask, ["location_name", "MIR", "YLLtoYLD", "DALtoPER", "PERtoINC"]].copy()

    label_map = {
        "Europe & Central Asia - WB": "Europe & Central Asia",
        "North America": "North America",
        "East Asia & Pacific - WB": "East Asia & Pacific",
        "Latin America & Caribbean - WB": "Latin Am. & Caribbean",
        "Middle East & North Africa - WB": "Middle East & N. Africa",
        "South Asia - WB": "South Asia",
        "Sub-Saharan Africa - WB": "Sub-Saharan Africa",
    }
    df["region_label"] = df["location_name"].map(label_map)

    region_order = [
        "North America",
        "Europe & Central Asia",
        "East Asia & Pacific",
        "Latin Am. & Caribbean",
        "Middle East & N. Africa",
        "South Asia",
        "Sub-Saharan Africa",
    ]

    comp_cols = ["MIR", "YLLtoYLD", "DALtoPER", "PERtoINC"]
    component_labels = [
        "Mortality-to-\nIncidence Ratio",
        "YLL-to-YLD\nRatio",
        "DALY-to-\nPrevalence Ratio",
        "Prevalence-to-\nIncidence Ratio",
    ]

    df = df.set_index("region_label")
    df = df.loc[region_order, comp_cols]
    df_display = df.copy()

    # Normalise each column to 0-1 for colour mapping
    df_norm = df.copy()
    for col in df_norm.columns:
        cmin = df_norm[col].min()
        cmax = df_norm[col].max()
        if cmax > cmin:
            df_norm[col] = (df_norm[col] - cmin) / (cmax - cmin)
        else:
            df_norm[col] = 0.5

    fig, ax = plt.subplots(figsize=(7, 5.5))
    cmap = sns.color_palette("RdYlGn_r", as_cmap=True)

    sns.heatmap(
        df_norm, ax=ax, cmap=cmap,
        annot=df_display.round(3).values, fmt="",
        linewidths=1.5, linecolor="white",
        cbar_kws={"label": "Relative magnitude (normalised)", "shrink": 0.8},
        xticklabels=component_labels,
        yticklabels=region_order,
        annot_kws={"fontsize": 9, "fontweight": "bold"},
    )

    ax.set_title("DS-TB Component Ratios by World Bank Region, 2021", fontsize=12, pad=12)
    ax.set_ylabel("")  # Remove automatic "region_label" y-axis label
    ax.tick_params(axis="x", rotation=0, labelsize=9)
    ax.tick_params(axis="y", rotation=0, labelsize=9)
    fig.tight_layout()
    savefig(fig, "figure6_component_heatmap")



# FIGURE 9 (manuscript): QCI Uncertainty Plot (selected locations, 1990 vs 2021)
# ======================================================================
def figure9():
    print("\nFigure 9: QCI Uncertainty Plot...")
    df = uncert.copy()

    df90 = df[df["year"] == 1990].sort_values("sort_key").reset_index(drop=True)
    df21 = df[df["year"] == 2021].sort_values("sort_key").reset_index(drop=True)

    locations = df90["display_name"].values
    n = len(locations)
    y_pos = np.arange(n)

    fig, ax = plt.subplots(figsize=(9, 8))
    bar_offset = 0.18

    # 1990
    ax.errorbar(
        df90["qci_point"].values, y_pos + bar_offset,
        xerr=[
            df90["qci_point"].values - df90["qci_lower"].values,
            df90["qci_upper"].values - df90["qci_point"].values,
        ],
        fmt="s", color="#4C72B0", ecolor="#4C72B0",
        elinewidth=1.3, capsize=3, capthick=1,
        markersize=5, markeredgecolor="white",
        markeredgewidth=0.5, label="1990", zorder=5,
    )

    # 2021
    ax.errorbar(
        df21["qci_point"].values, y_pos - bar_offset,
        xerr=[
            df21["qci_point"].values - df21["qci_lower"].values,
            df21["qci_upper"].values - df21["qci_point"].values,
        ],
        fmt="o", color="#C44E52", ecolor="#C44E52",
        elinewidth=1.3, capsize=3, capthick=1,
        markersize=5, markeredgecolor="white",
        markeredgewidth=0.5, label="2021", zorder=5,
    )

    ax.set_yticks(y_pos)
    ax.set_yticklabels(locations, fontsize=9)
    ax.set_xlabel("Quality of Care Index (QCI)", fontsize=11)
    ax.set_title(
        "DS-TB Quality of Care Index with 95% Uncertainty Intervals\n"
        "Selected Locations, 1990 vs 2021",
        fontsize=12, fontweight="bold",
    )
    ax.invert_yaxis()
    ax.grid(axis="x", alpha=0.2, linewidth=0.4)
    ax.legend(loc="lower right", frameon=True, fontsize=10, framealpha=0.9)

    # Separator lines between groups
    for sep_y in [0.5, 5.5, 12.5]:
        if sep_y < n:
            ax.axhline(sep_y, color="gray", linewidth=0.5, linestyle=":", alpha=0.5)

    # Category labels
    category_labels = {0: "Global", 1: "SDI Quintiles", 6: "WB Regions", 13: "Countries"}
    for idx, label in category_labels.items():
        if idx < n:
            ax.annotate(
                label,
                xy=(1.01, y_pos[idx]),
                xycoords=("axes fraction", "data"),
                fontsize=8, fontweight="bold",
                color="#666666", va="center",
            )

    fig.tight_layout()
    savefig(fig, "figure9_qci_uncertainty")



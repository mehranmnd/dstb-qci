# FIGURE 4 (manuscript): SDI Gradient Plot - QCI vs SDI scatter (2021)
# ======================================================================
def figure4():
    print("\nFigure 4: SDI Gradient Scatter Plot...")
    mask = (
        (qci_full["year"] == 2021)
        & (qci_full["age_name"] == "Age-standardized")
        & (qci_full["sex_name"] == "Both")
        & (qci_full["sdi_group"].notna())
        & (qci_full["sdi_value_2021"].notna())
    )
    df = qci_full.loc[mask].copy()

    fig, ax = plt.subplots(figsize=(7, 5.5))

    for grp in SDI_GROUP_ORDER:
        sub = df[df["sdi_group"] == grp]
        ax.scatter(
            sub["sdi_value_2021"], sub["pca_score"],
            c=SDI_GROUP_COLORS[grp],
            edgecolors="white", linewidths=0.3,
            s=40, alpha=0.8, label=grp, zorder=5,
        )

    # Polynomial (degree 3) trend line
    x = df["sdi_value_2021"].values
    y = df["pca_score"].values
    valid = np.isfinite(x) & np.isfinite(y)
    x, y = x[valid], y[valid]
    z = np.polyfit(x, y, 3)
    p = np.poly1d(z)
    xfit = np.linspace(x.min(), x.max(), 200)
    ax.plot(xfit, p(xfit), color="#333333", linewidth=2,
            linestyle="--", zorder=10, label="Polynomial fit")

    # Spearman rho
    rho, pval = stats.spearmanr(x, y)
    pval_str = "P < 0.001" if pval < 0.001 else "P = " + str(round(pval, 3))
    annot_text = "Spearman \u03C1 = " + str(round(rho, 3)) + "\n" + pval_str
    ax.annotate(
        annot_text,
        xy=(0.03, 0.03), xycoords="axes fraction",
        fontsize=10, fontweight="bold",
        bbox=dict(boxstyle="round,pad=0.4", facecolor="white",
                  edgecolor="gray", alpha=0.9),
    )

    ax.set_xlabel("Socio-demographic Index (SDI), 2021")
    ax.set_ylabel("Quality of Care Index (QCI), 2021")
    ax.set_title("Association Between SDI and DS-TB Quality of Care Index, 2021")
    ax.grid(alpha=0.2, linewidth=0.4)
    ax.legend(
        loc="upper center", bbox_to_anchor=(0.5, -0.12),
        ncol=3, frameon=False, fontsize=9, markerscale=1.3,
    )
    fig.tight_layout()
    savefig(fig, "figure4_sdi_gradient_scatter")



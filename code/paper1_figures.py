# FIGURE 8 (manuscript): Country AAPC Forest Plot (Top 15 + Bottom 15)
# ======================================================================
def figure8():
    print("\nFigure 8: Country AAPC Forest Plot...")
    countries = aapc_df[aapc_df["category"] == "COUNTRY"].copy()
    countries = countries.sort_values("aapc_full", ascending=False)

    top15 = countries.head(15).copy()
    bot15 = countries.tail(15).copy()
    bot15 = bot15.sort_values("aapc_full", ascending=True)

    fig, (ax1, ax2) = plt.subplots(
        1, 2, figsize=(11, 7), sharey=False,
        gridspec_kw={"wspace": 0.45},
    )

    def _forest(ax, data, title, color):
        y_pos = np.arange(len(data))
        xerr_lo = data["aapc_full"].values - data["ci_lo_full"].values
        xerr_hi = data["ci_hi_full"].values - data["aapc_full"].values

        ax.errorbar(
            data["aapc_full"].values, y_pos,
            xerr=[xerr_lo, xerr_hi],
            fmt="o", color=color, ecolor=color,
            elinewidth=1.2, capsize=3, capthick=1,
            markersize=5, markeredgecolor="white",
            markeredgewidth=0.5, zorder=5,
        )
        ax.axvline(0, color="gray", linewidth=0.8, linestyle="--", alpha=0.6)
        ax.set_yticks(y_pos)
        ax.set_yticklabels(data["location"].values, fontsize=9)
        ax.set_xlabel("AAPC (% per year)", fontsize=10)
        ax.set_title(title, fontsize=11, fontweight="bold")
        ax.grid(axis="x", alpha=0.2, linewidth=0.4)

        for i, row in enumerate(data.itertuples()):
            val = row.aapc_full
            ci_lo = row.ci_lo_full
            ci_hi = row.ci_hi_full
            txt = "{:.3f} ({:.3f}, {:.3f})".format(val, ci_lo, ci_hi)
            x_offset = ci_hi + 0.015
            ax.text(x_offset, i, txt, fontsize=8, va="center", color="#444444")

    _forest(ax1, top15, "Top 15 Countries\n(Largest QCI Improvement)", "#1a9850")
    _forest(ax2, bot15, "Bottom 15 Countries\n(Smallest / Negative QCI Change)", "#d73027")

    for ax in (ax1, ax2):
        xmin, xmax = ax.get_xlim()
        ax.set_xlim(xmin - 0.05, xmax + 0.25)

    fig.suptitle(
        "Average Annual Percentage Change (AAPC) in DS-TB QCI, 1990\u20132021",
        fontsize=12, fontweight="bold", y=0.98,
    )
    fig.tight_layout(rect=[0, 0, 1, 0.95])
    savefig(fig, "figure8_aapc_forest_plot")



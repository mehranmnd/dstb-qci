# FIGURE 3 (manuscript): Regional QCI Time Series (1990-2021)
# ======================================================================
def figure3():
    print("\nFigure 3: Regional QCI Time Series...")
    regions = list(REGION_COLORS.keys())
    mask = (
        (qci["location_name"].isin(regions))
        & (qci["age_name"] == "Age-standardized")
        & (qci["sex_name"] == "Both")
    )
    df = qci.loc[mask].copy()

    fig, ax = plt.subplots(figsize=(8, 5))

    for region in regions:
        sub = df[df["location_name"] == region].sort_values("year")
        lw = 2.5 if region == "Global" else 1.6
        zorder = 10 if region == "Global" else 5
        ax.plot(
            sub["year"], sub["pca_score"],
            color=REGION_COLORS[region],
            linewidth=lw,
            label=REGION_LABELS[region],
            zorder=zorder,
        )

    ax.set_xlabel("Year")
    ax.set_ylabel("Quality of Care Index (QCI)")
    ax.set_title("DS-TB Quality of Care Index by World Bank Region, 1990\u20132021")
    ax.set_xlim(1990, 2021)
    ax.set_ylim(88, 100)
    ax.yaxis.set_major_locator(ticker.MultipleLocator(2))
    ax.yaxis.set_minor_locator(ticker.MultipleLocator(1))
    ax.xaxis.set_major_locator(ticker.MultipleLocator(5))
    ax.grid(axis="y", alpha=0.3, linewidth=0.5)

    ax.legend(
        loc="upper center", bbox_to_anchor=(0.5, -0.14),
        ncol=4, frameon=False, fontsize=8.5,
    )
    fig.tight_layout()
    savefig(fig, "figure3_regional_qci_timeseries")


